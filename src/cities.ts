export const findCity = (name: string) => {
  const q = name.trim().toLowerCase();
  return CITIES.find((c) => c[0].toLowerCase() === q) ?? null;
};

const km = (aLat: number, aLng: number, bLat: number, bLng: number) => {
  const r = Math.PI / 180;
  const h = Math.sin(((bLat - aLat) * r) / 2) ** 2 + Math.cos(aLat * r) * Math.cos(bLat * r) * Math.sin(((bLng - aLng) * r) / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
};

export const countryOf = (s: { name: string; lat: number | null; lng: number | null; country?: string }): string => {
  if (s.country) return s.country;
  const c = findCity(s.name);
  if (c) return c[3];
  if (s.lat === null || s.lng === null) return '';
  let best = '';
  let bd = 150;
  for (const x of CITIES) {
    const d = km(s.lat, s.lng, x[1], x[2]);
    if (d < bd) {
      bd = d;
      best = x[3];
    }
  }
  return best;
};
